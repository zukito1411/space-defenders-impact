export function getCarrierCanopyProfile(key: string, landscape: boolean, groundedMech: boolean): Canopy | undefined {
  if (groundedMech) return mechPanels[key]
  return (landscape ? eliteSide[key] : eliteTop[key]) ?? profiles[key]?.[landscape ? 1 : 0]
}
