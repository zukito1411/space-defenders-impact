type Point = readonly [number, number]
type Canopy = { outline: readonly Point[]; hinge: Point; bounds: readonly [number, number, number, number]; hatch?: boolean }
type Views = readonly [Canopy, Canopy]

// Measured on the rendered hull in a 240-unit square. Side art is fitted to
// that square at its native aspect ratio. Portrait art fills the square.
function canopy(outline: readonly Point[], hinge: Point, hatch = false): Canopy {
  const xs = outline.map(([x]) => x), ys = outline.map(([, y]) => y)
  return { outline, hinge, hatch, bounds: [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)] }
}

