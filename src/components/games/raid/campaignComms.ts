export function getCampaignTransmission(language: LanguageCode, stage: number, debrief = false): readonly CommsLine[] | undefined {
  const scene = debrief ? ending : stage === 1 ? opening : stage === 5 ? pelagic : stage === 10 ? cinder : stage === 15 ? deepfield : stage === 16 ? devil : undefined
  return scene?.map(line => {
    const [speaker, , , , , direction] = line
    const channel = speaker === 'general' ? 'general' : speaker === 'reptilior' ? 'enemy' : undefined
    const sound = direction === 'laugh' ? 'laugh' :
      direction === 'furious' || direction === 'generalCut' || direction === 'static' ||
      direction === 'flagshipFire' || direction === 'retreat' ? 'static' : undefined
    const relayed = scene === deepfield && speaker === 'general'
    return [speaker, line[languageColumn[language]], channel, direction && directions[direction][directionColumn[language]], sound, relayed]
  })
}
